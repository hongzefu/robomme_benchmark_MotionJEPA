from scipy.stats import binom
def need(p, n=30, k=10): return binom.sf(k - 1, n, p)
print("== 抽签：P(Binom(n,p) >= 10)")
for p in (0.48, 0.483, 0.50, 0.40, 0.522, 0.27, 0.59, 0.5897, 0.665, 0.60, 0.526, 0.818):
    print(f"p={p:.4f}  n=30: {need(p):.4f}   n=40: {need(p,40):.5f}   n=60: {need(p,60):.6f}")
